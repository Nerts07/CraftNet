// Generate the 26.3 component skip table from the local protocol report.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const data = path.join(root, '.deps', 'mc26-data');
const { components } = require(path.join(data, 'packet_schema.json'));
const registries = require(path.join(data, 'registries.json'));
const ids = registries['minecraft:data_component_type'].entries;
const fn = node => `[&] { return ${read(node)}; }`;
function read(node) {
    switch (node.k) {
    case 'unit': return 'true';
    case 'enum': case 'registry': return 'var()';
    case 'string': case 'resourcekey': return 'string()';
    case 'nbt': return 'nbt()';
    case 'holder': return node.direct ? `holder(${fn(node.direct)})` : 'var()';
    case 'holderset': return 'holderSet()';
    case 'struct': return node.fields.map(f => read(f.type)).join(' && ') || 'true';
    case 'optional': return `optional(${fn(node.elem)})`;
    case 'either': return `either(${fn(node.left)}, ${fn(node.right)})`;
    case 'list': return `list(${fn(node.elem)}, ${node.max ?? 4096})`;
    case 'array': return `repeat(${node.size}, ${fn(node.elem)})`;
    case 'map': return `list([&] { return ${read(node.key)} && ${read(node.val)}; }, ${node.max ?? 4096})`;
    case 'ref':
        if (node.name === 'MobEffectInstance$Details') return 'effectDetails(depth + 1)';
        break;
    case 'dispatch': {
        const registry = registries[`minecraft:${node.key.registry}`]?.entries;
        const cases = node.cases.map(c => {
            const id = c.num ?? registry?.[c.id]?.protocol_id;
            if (id === undefined) throw Error(`Unknown dispatch ID: ${c.id}`);
            return `case ${id}: return ${read(c.type)};`;
        });
        return `dispatch([&](int id) { switch (id) { ${cases.join(' ')} default: return false; } })`;
    }
    case 'prim': {
        const primitives = {BOOL: 'r.skip(1)', INT: 'r.skip(4)', FLOAT: 'r.skip(4)', DOUBLE: 'r.skip(8)',
            UUID: 'r.skip(16)', BLOCK_POS: 'r.skip(8)', VAR_INT: 'var()', STRING: 'string()', IDENTIFIER: 'string()',
            NBT: 'nbt()', TEXT: 'nbt()', OPTIONAL_TEXT: 'optional([&] { return nbt(); })',
            COMPONENT_PATCH: 'patch(nullptr, depth + 1)', TYPED_DATA_COMPONENT: 'typed(nullptr, depth + 1)',
            GAME_PROFILE_PROPERTIES: 'list([&] { return string() && string() && optional([&] { return string(); }); }, 64)'};
        if (primitives[node.t]) return primitives[node.t];
        break;
    }
    }
    throw Error(`Unsupported schema node: ${JSON.stringify(node)}`);
}
const lines = ['// Generated by tools/build_item_components.js.'];
for (const [name, entry] of Object.entries(components)) {
    lines.push(`case ${ids[name].protocol_id}: // ${name}`, `    return ${read(entry.type)};`);
}
fs.writeFileSync(path.join(root, 'src', 'item_components.inc'), lines.join('\n') + '\n');
const enchantments = require(path.join(data, 'component_hashes.json')).registries['minecraft:enchantment'];
const names = enchantments.map(id => JSON.stringify(id.slice('minecraft:'.length).replaceAll('_', ' ')) + ',');
fs.writeFileSync(path.join(root, 'src', 'item_enchantments.inc'), '// Vanilla registry order for protocol 777.\n' +
    names.join('\n') + '\n');
